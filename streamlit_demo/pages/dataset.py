"""Dataset page: explore the synthetic training data."""
from __future__ import annotations

import altair as alt
import pandas as pd
import streamlit as st

from streamlit_demo.data import load_dataset
from streamlit_demo.ui import CATEGORY_ORDER, feature_label


def _class_balance_chart(frame: pd.DataFrame) -> alt.Chart:
    counts = frame["performance_category"].value_counts().rename_axis("Category").reset_index(name="Students")
    return (
        alt.Chart(counts)
        .mark_bar(cornerRadiusTopLeft=4, cornerRadiusTopRight=4)
        .encode(
            x=alt.X("Category:N", sort=CATEGORY_ORDER, title=None),
            y=alt.Y("Students:Q"),
            color=alt.Color("Category:N", sort=CATEGORY_ORDER, legend=None),
            tooltip=[alt.Tooltip("Category:N"), alt.Tooltip("Students:Q")],
        )
        .properties(height=300)
    )


def _gpa_histogram(frame: pd.DataFrame) -> alt.Chart:
    return (
        alt.Chart(frame)
        .mark_bar(color="#0f172a")
        .encode(
            x=alt.X("final_gpa:Q", bin=alt.Bin(maxbins=30), title="Final GPA"),
            y=alt.Y("count():Q", title="Students"),
            tooltip=[alt.Tooltip("count():Q", title="Students")],
        )
        .properties(height=300)
    )


def _correlation_heatmap(frame: pd.DataFrame) -> alt.Chart:
    numeric = frame.select_dtypes("number")
    correlation = numeric.corr(numeric_only=True).round(2).reset_index()
    correlation = correlation.rename(columns={correlation.columns[0]: "Row feature"})
    long = correlation.melt(id_vars="Row feature", var_name="Column feature", value_name="Correlation")

    return (
        alt.Chart(long)
        .mark_rect(stroke="#ffffff", strokeWidth=1)
        .encode(
            x=alt.X("Column feature:N", title=None, axis=alt.Axis(labelAngle=-45)),
            y=alt.Y("Row feature:N", title=None),
            color=alt.Color(
                "Correlation:Q",
                scale=alt.Scale(scheme="redblue", domain=[-1, 1]),
                title="Correlation",
            ),
            tooltip=[
                alt.Tooltip("Row feature:N"),
                alt.Tooltip("Column feature:N"),
                alt.Tooltip("Correlation:Q", format=".2f"),
            ],
        )
        .properties(height=430)
    )


def render() -> None:
    st.title("Synthetic dataset explorer")
    st.warning(
        "**This data is not real.** Every row was procedurally generated by "
        "`scripts/generate_dataset.py` with hand-designed relationships and noise. It must never "
        "be presented as real institutional or student data."
    )

    frame = load_dataset()

    rows, features, average_gpa, at_risk = st.columns(4)
    rows.metric("Students", f"{len(frame):,}")
    features.metric("Features", len(frame.columns) - 2)
    average_gpa.metric("Mean final GPA", f"{frame['final_gpa'].mean():.2f}")
    at_risk.metric("At-risk rows", f"{(frame['performance_category'] == 'At Risk').sum():,}")

    left, right = st.columns(2)
    with left:
        st.subheader("Class balance")
        st.altair_chart(_class_balance_chart(frame), width="stretch")
    with right:
        st.subheader("Final GPA distribution")
        st.altair_chart(_gpa_histogram(frame), width="stretch")

    st.subheader("Feature correlation")
    st.caption(
        "Correlations are properties of the synthetic generator. They are not claims about real "
        "student populations."
    )
    st.altair_chart(_correlation_heatmap(frame), width="stretch")

    st.subheader("Summary statistics")
    summary = frame.describe().T.reset_index().rename(columns={"index": "Column"})
    summary["Column"] = summary["Column"].map(feature_label)
    st.dataframe(summary.style.format({column: "{:.2f}" for column in summary.columns if column != "Column"}),
                 hide_index=True, width="stretch")

    st.subheader("Sample rows")
    st.dataframe(frame.head(25), hide_index=True, width="stretch")

    st.caption(
        "Columns: 11 model features plus the regression target (`final_gpa`) and the derived "
        "classification target (`performance_category`)."
    )
